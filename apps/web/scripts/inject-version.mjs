// Reads apps/web/package.json version and writes it into
// src/generated/version.js so the bundle has it baked in.
//
// Runs automatically before `npm run dev` and `npm run build`
// via the "predev" / "prebuild" npm scripts.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgPath   = resolve(__dirname, '../package.json');
const outDir    = resolve(__dirname, '../src/generated');
const outFile   = resolve(outDir, 'version.js');

const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
const version = pkg.version || '0.0.0-unknown';

if (existsSync(outFile)) {
  const existing = readFileSync(outFile, 'utf8');
  if (existing.includes(`APP_VERSION = "${version}"`)) {
    console.log(`[inject-version] ${version} already injected, skipping`);
    process.exit(0);
  }
}

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const content = `// AUTO-GENERATED by scripts/inject-version.mjs - do not edit.
// Bump via: node scripts/bump-version.mjs <new-version>
export const APP_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(outFile, content, 'utf8');
console.log(`[inject-version] wrote ${version} to src/generated/version.js`);
